import { cpSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const panelRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaPath = process.env.EMAIL_BLOCK_SCHEMA
  ?? resolve(panelRoot, '../unit-hq-api/resources/schemas/email-block-document.v2.json')

const schema = JSON.parse(readFileSync(schemaPath, 'utf8')) as {
  $defs: {
    section: { properties: { layout: { enum: Array<string> } } }
    block: { properties: { type: { enum: Array<string> } } }
    sectionParams: { properties: { padding: { enum: Array<string> } } }
  }
}

const expectedLayouts = ['100', '50_50', '33_67', '67_33', '33_33_33']
const layouts = schema.$defs.section.properties.layout.enum
if (JSON.stringify(layouts) !== JSON.stringify(expectedLayouts)) {
  throw new Error(`Unexpected layouts in schema: ${layouts.join(', ')}`)
}

const expectedTypes = [
  'heading',
  'paragraph',
  'button',
  'image',
  'divider',
  'spacer',
  'unit_summary',
  'raw_html',
  'info_rows',
  'list',
  'callout',
  'logo_header',
  'footer_social'
]
const blockTypes = schema.$defs.block.properties.type.enum
for (const type of expectedTypes) {
  if (!blockTypes.includes(type)) {
    throw new Error(`Schema missing block type ${type}`)
  }
}

const paddings = schema.$defs.sectionParams.properties.padding.enum
const expectedPadding = ['none', 'sm', 'md', 'lg']
if (JSON.stringify(paddings) !== JSON.stringify(expectedPadding)) {
  throw new Error(`Unexpected padding tokens: ${paddings.join(', ')}`)
}

const out = `// Generated by scripts/gen-email-block-types.ts from the email block document v2 schema. Do not edit.

export type EmailLayout = '100' | '50_50' | '33_67' | '67_33' | '33_33_33'

export type EmailPadding = 'none' | 'sm' | 'md' | 'lg'

export type SocialNetwork = 'facebook' | 'instagram' | 'linkedin' | 'x' | 'youtube' | 'tiktok' | 'website'

export interface EmailDocumentSettings {
  background_color?: string | null
}

export interface EmailSectionParams {
  background_color?: string | null
  padding: EmailPadding
  stack_on_mobile?: boolean
}

export interface EmailV2Block {
  id: string
  type: string
  params: Record<string, unknown>
}

export interface EmailColumn {
  id: string
  blocks: Array<EmailV2Block>
}

export interface EmailSection {
  id: string
  layout: EmailLayout
  params: EmailSectionParams
  columns: Array<EmailColumn>
}

export interface EmailDocumentV2 {
  version: 2
  settings?: EmailDocumentSettings
  sections: Array<EmailSection>
}

export interface InfoRow {
  label: string
  value: string
}

export interface InfoRowsBlockParams {
  rows: Array<InfoRow>
  striped: boolean
  value_align: 'left' | 'right'
}

export interface ListBlockParams {
  style: 'bullet' | 'numbered'
  items: Array<string>
}

export interface CalloutBlockParams {
  tone: 'info' | 'warning' | 'danger'
  title?: string | null
  html: string
}

export interface LogoHeaderBlockParams {
  align: 'left' | 'center'
  max_width: number
  link_url?: string | null
}

export interface SocialLink {
  network: SocialNetwork
  url: string
}

export interface FooterSocialBlockParams {
  links: Array<SocialLink>
  address?: string | null
}
`

if (/[A-Za-z0-9>]\[\]/.test(out)) {
  throw new Error('Generated types must use Array<T>')
}

const typesPath = resolve(panelRoot, 'app/types/email-block-document.ts')
writeFileSync(typesPath, out)

const apiRoot = resolve(dirname(schemaPath), '../..')
const fixtureSrc = resolve(apiRoot, 'tests/Fixtures/email-blocks/v2/valid')
const fixtureDest = resolve(panelRoot, 'tests/fixtures/email-blocks/v2/valid')
mkdirSync(fixtureDest, { recursive: true })
cpSync(fixtureSrc, fixtureDest, { recursive: true })
